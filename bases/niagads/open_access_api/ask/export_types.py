"""Export ASK's shared type vocabulary for the TypeScript client."""

import argparse
import json
from pathlib import Path

from niagads.api.common.types import AnnotationKind
from niagads.common.core import ComponentBaseMixin
from niagads.common.types import Entity
from niagads.open_access_api.ask.contracts import SOURCE_CHART_TYPES


class AskTypeExporter(ComponentBaseMixin):
    """Generate frontend constants from the Python enums and presentation rules."""

    def write(self, destination: Path) -> None:
        """Write the generated TypeScript module.

        Args:
            destination (Path): Output module in the frontend checkout.
        """
        constants = {
            "Entity": {member.name: member.value for member in Entity},
            "AnnotationKind": {
                member.name: member.value for member in AnnotationKind
            },
            "sourceChartTypes": [
                {"entity": entity.value, "annotation": annotation.value}
                for entity, annotation in SOURCE_CHART_TYPES
            ],
        }
        lines = [
            "// Generated by niagads.open_access_api.ask.export_types; do not edit.",
        ]
        for name, value in constants.items():
            lines.append(
                f"export const {name} = {json.dumps(value, indent=4)} as const;"
            )
        destination.write_text("\n\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("destination", type=Path)
    AskTypeExporter().write(parser.parse_args().destination)
